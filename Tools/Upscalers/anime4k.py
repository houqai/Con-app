#!/usr/bin/env python3
import re
import sys

source = open(sys.argv[1]).read()
header = source[:source.index("//!DESC")]
passes = []
for block in source.split("//!DESC")[1:]:
    lines = block.split("\n")
    name = lines[0].strip()
    binds = re.findall(r"//!BIND (\w+)", block)
    save = re.search(r"//!SAVE (\w+)", block).group(1)
    if "Depth-to-Space" in name:
        passes.append({"kind": "space", "name": name})
        continue
    gos = {}
    for go, negative, texture in re.findall(r"#define go_(\d)\(x_off, y_off\) \((max\(-|max\(|)\(?(\w+?)_texOff", block):
        gos[go] = {"relu": negative != "", "negative": negative == "max(-", "texture": texture}
    terms = []
    for values, go, x, y in re.findall(r"mat4\(([^)]*)\) \* go_(\d)\(([-0-9.]+), ([-0-9.]+)\)", block):
        numbers = [v.strip() for v in values.split(",")]
        assert len(numbers) == 16, name
        terms.append((numbers, go, float(x), float(y)))
    bias = re.search(r"result \+= vec4\(([^)]*)\);", block).group(1)
    passes.append({"kind": "conv", "name": name, "input": binds[0], "save": save, "gos": gos, "terms": terms, "bias": bias})

def number(v):
    v = v.strip()
    return v if any(c in v for c in ".e") else v + ".0"

def body(p, dialect):
    out = []
    for go, info in p["gos"].items():
        sign = "-" if info["negative"] else ""
        relu = info["relu"]
        if dialect == "hlsl":
            fetch = "source[clamp(at + int2(dx, dy), int2(0, 0), last)]"
        else:
            fetch = "source.read(uint2(clamp(at + int2(dx, dy), int2(0, 0), last)))"
        expr = f"max({sign}{fetch}, 0.0)" if relu else fetch
        out.append(f"#define GO_{go}(dx, dy) ({expr})")
    out.append("    float4 result = float4(0.0, 0.0, 0.0, 0.0);")
    for numbers, go, x, y in p["terms"]:
        n = [number(v) for v in numbers]
        if dialect == "hlsl":
            out.append(f"    result += mul(GO_{go}({int(x)}, {int(y)}), float4x4({', '.join(n)}));")
        else:
            cols = ", ".join(f"float4({', '.join(n[i:i+4])})" for i in range(0, 16, 4))
            out.append(f"    result += float4x4({cols}) * GO_{go}({int(x)}, {int(y)});")
    out.append(f"    result += float4({', '.join(number(v) for v in p['bias'].split(','))});")
    for go in p["gos"]:
        out.append(f"#undef GO_{go}")
    return "\n".join(out)

convs = [p for p in passes if p["kind"] == "conv"]
assert passes[-1]["kind"] == "space" and len(convs) >= 2
notice = "\n".join("// " + line[3:] if line.startswith("// ") else "//" + line[2:] for line in header.strip().split("\n"))
intro = f"// Generated by Tools/Upscalers/anime4k.py from {sys.argv[1].split('/')[-1]} (Anime4K, bloc97):\n{notice}\n"

hlsl = [intro,
        "Texture2D<float4> source : register(t0);", "Texture2D<float4> picture : register(t1);",
        "RWTexture2D<float4> target : register(u0);", "SamplerState smooth : register(s1);", ""]
for i, p in enumerate(convs):
    hlsl.append(f"[numthreads(8, 8, 1)] void anime4k_{i}(uint3 id : SV_DispatchThreadID) {{")
    hlsl.append("    uint w, h; source.GetDimensions(w, h);")
    hlsl.append("    if (id.x >= w || id.y >= h) return;")
    hlsl.append("    int2 at = int2(id.xy), last = int2(w, h) - 1;")
    hlsl.append(body(p, "hlsl"))
    hlsl.append("    target[id.xy] = result;")
    hlsl.append("}\n")
hlsl.append("""[numthreads(8, 8, 1)] void anime4k_space(uint3 id : SV_DispatchThreadID) {
    uint w, h; target.GetDimensions(w, h);
    if (id.x >= w || id.y >= h) return;
    float4 detail = source[id.xy / 2];
    uint which = (id.y % 2) * 2 + (id.x % 2);
    float d = which == 0 ? detail.x : which == 1 ? detail.y : which == 2 ? detail.z : detail.w;
    float2 place = (float2(id.xy) + 0.5) / float2(w, h);
    target[id.xy] = float4(saturate(picture.SampleLevel(smooth, place, 0).rgb + d), 1.0);
}""")
open(sys.argv[2], "w").write("\n".join(hlsl) + "\n")

metal = [intro, ""]
for i, p in enumerate(convs):
    metal.append(f"kernel void anime4k_{i}(texture2d<float, access::read> source [[texture(0)]], texture2d<float, access::write> target [[texture(1)]], uint2 id [[thread_position_in_grid]]) {{")
    metal.append("    int w = source.get_width(), h = source.get_height();")
    metal.append("    if (int(id.x) >= w || int(id.y) >= h) return;")
    metal.append("    int2 at = int2(id), last = int2(w, h) - 1;")
    metal.append(body(p, "metal"))
    metal.append("    target.write(result, id);")
    metal.append("}\n")
metal.append("""kernel void anime4k_space(texture2d<float, access::read> source [[texture(0)]], texture2d<float, access::write> target [[texture(1)]],
                          texture2d<float, access::sample> picture [[texture(2)]], uint2 id [[thread_position_in_grid]]) {
    uint w = target.get_width(), h = target.get_height();
    if (id.x >= w || id.y >= h) return;
    float4 detail = source.read(id / 2);
    uint which = (id.y % 2) * 2 + (id.x % 2);
    float d = which == 0 ? detail.x : which == 1 ? detail.y : which == 2 ? detail.z : detail.w;
    constexpr sampler smooth(coord::normalized, filter::linear, address::clamp_to_edge);
    float2 place = (float2(id) + 0.5) / float2(w, h);
    target.write(float4(saturate(picture.sample(smooth, place).rgb + d), 1.0), id);
}""")
text = "\n".join(metal) + "\n"
swift = "enum Anime4KShader {\n"
swift += "    static let passes = [" + ", ".join(f'"anime4k_{i}"' for i in range(len(convs))) + "]\n"
swift += '    static let source = """\n' + text.replace("\\", "\\\\") + '"""\n}\n'
open(sys.argv[3], "w").write(swift)
print(f"{len(convs)} convolutions + depth to space")
